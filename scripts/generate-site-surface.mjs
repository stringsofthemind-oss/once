import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
const read = (file) => readFileSync(resolve(root, file), 'utf8').replaceAll('\r\n', '\n');
const published = JSON.parse(read('docs/published-versions.json'));
const python = read('sdk/python/pyproject.toml').match(/^version\s*=\s*"([^"]+)"/m)[1];
export const versions = { ts: published.ts, python, mcp: published.mcp };
// Published metadata, not an unreleased source version, is the install authority.
const files = [
	'docs/index.html',
	'docs/demo/index.html',
	'docs/quickstart/index.html',
	'docs/evidence/index.html',
	'docs/retry-exposure/index.html',
];
const outputs = new Map();
for (const file of files) {
	let value = read(file);
	for (const [name, version] of Object.entries(versions)) {
		value = value.replace(new RegExp(`(data-version="${name}">)[^<]*`, 'g'), `$1${version}`);
	}
	value = value.replace(/@once-agent\/sdk@\d+\.\d+\.\d+/g, `@once-agent/sdk@${versions.ts}`);
	value = value.replace(/("softwareVersion"\s*:\s*")[^"]+/, `$1${versions.ts}`);
	outputs.set(file, value);
}
// Embed the same simulation/assets in the Worker; no cross-host dependency.
let demo = outputs.get('docs/demo/index.html');
demo = demo.replace('<link rel="stylesheet" href="/funnel.css">', `<style>${read('docs/funnel.css')}</style>`);
for (const script of ['page-analytics.js', 'funnel.js', 'retry-demo.js']) {
	demo = demo.replace(`<script src="/${script}" defer></script>`, '');
}
demo = demo.replace(/href="\/(?!\/)([^"#]*)"/g, (_, suffix) => `href="https://onceexec.com/${suffix}"`);
demo = demo.replace('</body>', `<script>${read('docs/retry-demo.js').replaceAll('</script', '<\\/script')}</script></body>`);
outputs.set(
	'workers/playground/src/retry-demo-page.js',
	`// Generated by scripts/generate-site-surface.mjs; do not hand-edit.\nexport default ${JSON.stringify(demo)};\n`,
);
let changed = false;
for (const [file, value] of outputs) {
	let current = '';
	try {
		current = read(file);
	} catch {}
	if (current !== value) {
		changed = true;
		if (!process.argv.includes('--check')) writeFileSync(resolve(root, file), value);
		else console.error(`Out-of-date generated surface: ${file}`);
	}
}
if (process.argv.includes('--check') && changed) process.exitCode = 1;
else console.log(`Site versions and shared demo checked: ${JSON.stringify(versions)}`);
